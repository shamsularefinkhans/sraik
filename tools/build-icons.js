/**
 * build-icons.js — generates wp-content/sraik-templates/inc/icons.php from
 * lucide-static. Only the names in ICONS are shipped. Run: npm run icons
 */
const fs = require('fs');
const path = require('path');
const ICONS = require('./icons.json');
const dir = path.join(__dirname, 'node_modules/lucide-static/icons');
const out = [];
for (const name of ICONS) {
  const file = path.join(dir, name + '.svg');
  if (!fs.existsSync(file)) { console.error('missing icon: ' + name); process.exit(1); }
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/<!--.*?-->/s, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
  out.push(`\t\t'${name}' => '${inner.replace(/'/g, "\\'")}',`);
}
const php = `<?php
/**
 * icons.php — GENERATED by tools/build-icons.js from lucide-static (ISC).
 * Do not edit by hand: add the name to tools/icons.json and run npm run icons.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

function sraik_icon_paths() {
	return array(
${out.join('\n')}
	);
}

/**
 * Inline SVG icon. $size in px; stroke width follows the template (1.6–2).
 */
function sraik_icon( $name, $size = 16, $stroke = 2, $class = '' ) {
	$paths = sraik_icon_paths();
	if ( ! isset( $paths[ $name ] ) ) {
		return '';
	}
	return '<svg class="ico' . ( $class ? ' ' . esc_attr( $class ) : '' ) . '" width="' . (int) $size . '" height="' . (int) $size . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' . esc_attr( $stroke ) . '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' . $paths[ $name ] . '</svg>';
}

/** Echo an icon. */
function sraik_i( $name, $size = 16, $stroke = 2, $class = '' ) {
	echo sraik_icon( $name, $size, $stroke, $class ); // phpcs:ignore WordPress.Security.EscapeOutput
}
`;
fs.writeFileSync(path.join(__dirname, '../wp-content/sraik-templates/inc/icons.php'), php);
console.log('icons.php: ' + ICONS.length + ' icons');
